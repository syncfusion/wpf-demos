namespace syncfusion.chartdemos.wpf
{
    /// <summary>Represents a data item for step line charts.</summary>
    public class StepLineChartModel
    {
        /// <summary>Gets or sets the category label.</summary>
        public string Name { get; set; }

        /// <summary>Gets or sets the single series value.</summary>
        public double Value { get; set; }

        /// <summary>Gets or sets the value for India.</summary>
        public double India { get; set; }

        /// <summary>Gets or sets the value for Germany.</summary>
        public double Germany { get; set; }

        /// <summary>Gets or sets the value for Kazakhstan.</summary>
        public double Kazakhstan { get; set; }
    }
}
