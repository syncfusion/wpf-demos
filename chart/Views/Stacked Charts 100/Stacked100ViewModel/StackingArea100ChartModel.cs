namespace syncfusion.chartdemos.wpf
{
    /// <summary>Represents yearly country values for 100% stacked area charts.</summary>
    public class StackedArea100Model
    {
        /// <summary>Gets or sets the year label.</summary>
        public string Year { get; set; }

        /// <summary>Gets or sets the value for Peru.</summary>
        public double Peru { get; set; }

        /// <summary>Gets or sets the value for Canada.</summary>
        public double Canada { get; set; }

        /// <summary>Gets or sets the value for Ethiopia.</summary>
        public double Ethiopia { get; set; }

        /// <summary>Gets or sets the value for Mali.</summary>
        public double Mali { get; set; }
    }
}
