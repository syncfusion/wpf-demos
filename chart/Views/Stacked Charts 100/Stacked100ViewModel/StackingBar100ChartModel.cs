namespace syncfusion.chartdemos.wpf
{
    /// <summary>Represents market share values for 100% stacked bar charts.</summary>
    public class StackedBar100Model
    {
        /// <summary>Gets or sets the period label.</summary>
        public string Year { get; set; }

        /// <summary>Gets or sets the value for Others.</summary>
        public double Others { get; set; }

        /// <summary>Gets or sets the value for Volkswagen Group.</summary>
        public double VolkswagenGroup { get; set; }

        /// <summary>Gets or sets the value for Tesla.</summary>
        public double Tesla { get; set; }

        /// <summary>Gets or sets the value for BYD Auto.</summary>
        public double BYDAuto { get; set; }
    }
}
