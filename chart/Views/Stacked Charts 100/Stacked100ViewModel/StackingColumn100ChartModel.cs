namespace syncfusion.chartdemos.wpf
{
    /// <summary>Represents electricity consumption percentages for 100% stacked columns.</summary>
    public class StackedColumn100Model
    {
        /// <summary>Gets or sets the country name.</summary>
        public string CountryName { get; set; }

        /// <summary>Gets or sets the industry share.</summary>
        public double Industry { get; set; }

        /// <summary>Gets or sets the public services share.</summary>
        public double PublicServices { get; set; }

        /// <summary>Gets or sets the residential share.</summary>
        public double Residential { get; set; }

        /// <summary>Gets or sets the others share.</summary>
        public double Others { get; set; }
    }
}
